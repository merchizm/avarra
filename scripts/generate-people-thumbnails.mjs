import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { peopleImages } from '../docs/.vitepress/theme/data/peopleImages.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const illustrationRoot = path.join(root, 'docs/public/assets/illustrations')
const thumbnailRoot = path.join(illustrationRoot, 'thumbs')
const manifestPath = path.join(root, 'docs/.vitepress/theme/data/peopleThumbnails.js')

fs.mkdirSync(thumbnailRoot, { recursive: true })

const thumbnails = {}
for (const asset of [...new Set(Object.values(peopleImages))].sort()) {
  const sourcePath = path.join(root, 'docs/public', asset)
  if (!fs.existsSync(sourcePath)) throw new Error(`Portrait source is missing: ${asset}`)

  const hash = createHash('sha256').update(fs.readFileSync(sourcePath)).digest('hex').slice(0, 12)
  const basename = path.basename(asset, path.extname(asset))
  const thumbnailName = `${basename}-${hash}.webp`
  const thumbnailPath = path.join(thumbnailRoot, thumbnailName)

  if (!fs.existsSync(thumbnailPath)) {
    execFileSync('magick', [
      sourcePath,
      '-auto-orient',
      '-resize', '640x640>',
      '-strip',
      '-quality', '80',
      '-define', 'webp:method=6',
      thumbnailPath
    ], { stdio: 'inherit' })
  }

  thumbnails[asset] = `/assets/illustrations/thumbs/${thumbnailName}`
}

const manifest = `// Generated by scripts/generate-people-thumbnails.mjs. Do not edit manually.\nexport const peopleThumbnails = ${JSON.stringify(thumbnails, null, 2)}\n`
if (!fs.existsSync(manifestPath) || fs.readFileSync(manifestPath, 'utf8') !== manifest) {
  fs.writeFileSync(manifestPath, manifest)
}

console.log(`People thumbnails ready: ${Object.keys(thumbnails).length}`)
